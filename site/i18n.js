// English is the source: a key missing from another language falls back to it,
// so a page never keeps the previous language's text after a switch.
// Storage can throw (private windows, blocked site data): every access is guarded.

function readSavedLang() {
  try { return localStorage.getItem("wmux-lang"); } catch { return null; }
}

function saveLang(lang) {
  try { localStorage.setItem("wmux-lang", lang); } catch { /* storage unavailable: the hash still carries the choice */ }
}

function normalizeLang(code) {
  if (!code) return null;
  const lower = code.toLowerCase();
  if (lower === "zh-tw" || lower === "zh-hant" || lower === "zh-hk") return "zh-TW";
  if (T[code]) return code;
  if (T[lower]) return lower;
  return null;
}

function detectLang() {
  // 1. URL hash (#fr, #ar, ...). In-page anchors (#install) are not language codes and are ignored.
  const fromHash = normalizeLang(location.hash.replace("#", ""));
  if (fromHash) return fromHash;

  // 2. Saved preference
  const saved = normalizeLang(readSavedLang());
  if (saved) return saved;

  // 3. Browser language: exact, then Chinese script, then base
  const nav = navigator.language || "en";
  if (T[nav]) return nav;
  const base = nav.split("-")[0].toLowerCase();
  if (base === "zh") return /Hant|TW|HK/.test(nav) ? "zh-TW" : "zh";
  return T[base] ? base : "en";
}

function translate(lang, key) {
  const own = T[lang] && T[lang][key];
  return own != null ? own : T.en[key];
}

// The share and bookmark metadata follows the language, so a localized hash URL never has a mixed-language head.
// English keeps the hand-written tags (read once, restored on a switch back); other languages reuse the
// translated title and hero lead. Crawlers only see the English page without a hash.
const HEAD_META = [
  ['meta[name="description"]', "hero.lead"],
  ['meta[property="og:title"]', "meta.title"],
  ['meta[property="og:description"]', "hero.lead"],
  ['meta[name="twitter:title"]', "meta.title"],
  ['meta[name="twitter:description"]', "hero.lead"]
];

function applyHeadMeta(lang) {
  HEAD_META.forEach(([selector, key]) => {
    const tag = document.head.querySelector(selector);
    if (!tag) return;
    if (tag.dataset.en == null) tag.dataset.en = tag.getAttribute("content") || "";
    tag.setAttribute("content", lang === "en" ? tag.dataset.en : translate(lang, key));
  });
}

